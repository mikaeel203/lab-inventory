test("signup offers a rate-limited confirmation resend and spam reminder", async ({ page }) => {
  await page.clock.install();
  const resends: { email: string; type: string; redirect: string | null }[] = [];
  await page.route("**/auth/v1/resend**", async route => {
    const body = route.request().postDataJSON();
    resends.push({ email: body.email, type: body.type, redirect: new URL(route.request().url()).searchParams.get("redirect_to") });
    if (resends.length === 2) await route.fulfill({ status: 429, json: { code: "over_email_send_rate_limit", msg: "Email rate limit exceeded. Try again later." } });
    else await route.fulfill({ json: {} });
  });
  await page.goto("/auth");
  await page.getByRole("button", { name: "Create an account", exact: true }).click();
  await page.getByRole("button", { name: "Student account" }).click();
  await page.getByLabel("Your name").fill("Email Student");
  await page.getByLabel("Email address").fill("resend@example.test");
  await page.getByLabel("Password", { exact: true }).fill("test-password-123");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("spam/junk");
  const resend = page.getByRole("button", { name: /Resend confirmation email/ });
  await expect(resend).toBeDisabled();
  expect(resends).toHaveLength(0);
  await page.clock.fastForward(61_000);
  await expect(resend).toBeEnabled();
  await resend.click();
  await expect(page.getByRole("status")).toContainText("requested again");
  await expect(resend).toBeDisabled();
  expect(resends).toEqual([{ email: "resend@example.test", type: "signup", redirect: "http://127.0.0.1:3100/auth/confirm" }]);
  await page.clock.fastForward(61_000);
  await resend.click();
  await expect(page.getByRole("alert").filter({ hasText: "rate limit" })).toBeVisible();
  await expect(resend).toBeDisabled();
  await page.clock.fastForward(61_000);
  await expect(resend).toBeEnabled();
});

